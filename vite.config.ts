import { readdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { defineConfig, type Plugin } from 'vite';
import react from '@vitejs/plugin-react';

/**
 * Writes `sw.js` (offline support) into dist/ on `vite build`:
 * - precaches index.html, every emitted JS/CSS file, the woff2 fonts and the files in public/;
 * - navigations (index.html): network first, cached copy when offline → new versions arrive at once;
 * - every other same-origin GET: cache first (file names are content-hashed), cached on first use;
 * - the cache name contains a hash of the file list, old caches are deleted on activate.
 * Registered by src/pwa.ts in production builds only.
 */
function serviceWorker(): Plugin {
  return {
    name: 'matek-kaland-sw',
    apply: 'build',
    generateBundle(_options, bundle) {
      const emitted = Object.keys(bundle).filter((f) => !/\.(woff|ttf|map)$/.test(f));
      const publicFiles = readdirSync(new URL('./public', import.meta.url)).filter((f) => !f.startsWith('.'));
      const files = ['./', 'index.html', ...publicFiles, ...emitted].filter((f, i, a) => a.indexOf(f) === i);
      const version = createHash('sha256').update(files.sort().join('\n')).digest('hex').slice(0, 12);
      const source = `// Generated by vite.config.ts — do not edit.
const CACHE = 'matek-kaland-${version}';
const PRECACHE = ${JSON.stringify(files)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('matek-kaland-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put('index.html', copy));
          return res;
        })
        .catch(() => caches.match('index.html').then((r) => r || caches.match('./'))),
    );
    return;
  }
  event.respondWith(
    caches.match(req).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok && res.type === 'basic') {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(req, copy));
          }
          return res;
        }),
    ),
  );
});
`;
      this.emitFile({ type: 'asset', fileName: 'sw.js', source });
    },
  };
}

// base: './' keeps the build working on any static host path (Cloudflare Pages, GitHub Pages).
export default defineConfig({
  plugins: [react(), serviceWorker()],
  base: './',
});
